    "' LOAD RECORDS CSV INTO SHEET (8 columns, quote-aware)\r\n"
    "' =============================================================\r\n"
    "Private Sub LoadRecordsCSV(csvPath As String)\r\n"
    "    Dim wsR As Worksheet\r\n"
    "    Dim lastR As Long\r\n"
    "    Dim fn As Integer\r\n"
    "    Dim openErr As Long\r\n"
    "    Dim lineText As String\r\n"
    "    Dim r As Long\r\n"
    "    Dim fields() As String\r\n"
    "    Dim nFields As Long\r\n"
    "    Dim c As Long\r\n"
    "\r\n"
    "    On Error Resume Next\r\n"
    "    Set wsR = ThisWorkbook.Sheets(\"Records\")\r\n"
    "    On Error GoTo 0\r\n"
    "    If wsR Is Nothing Then Exit Sub\r\n"
    "    ' Clear data rows (row 2 onward)\r\n"
    "    lastR = wsR.Cells(wsR.Rows.Count, 1).End(xlUp).Row\r\n"
    "    If lastR >= 2 Then\r\n"
    "        wsR.Range(\"A2:H\" & lastR).ClearContents\r\n"
    "    End If\r\n"
    "    ' Open the CSV file\r\n"
    "    fn = FreeFile\r\n"
    "    Err.Clear\r\n"
    "    On Error Resume Next\r\n"
    "    Open csvPath For Input As #fn\r\n"
    "    openErr = Err.Number\r\n"
    "    On Error GoTo 0\r\n"
    "    If openErr <> 0 Then Exit Sub\r\n"
    "    ' Read line by line, parsing each via ParseCSVLine\r\n"
    "    r = 1\r\n"
    "    If Not EOF(fn) Then Line Input #fn, lineText\r\n"
    "    Do While Not EOF(fn)\r\n"
    "        r = r + 1\r\n"
    "        Line Input #fn, lineText\r\n"
    "        ParseCSVLine lineText, fields, nFields\r\n"
    "        For c = 0 To nFields - 1\r\n"
    "            If c < 8 Then wsR.Cells(r, c + 1).Value = fields(c)\r\n"
    "        Next c\r\n"
    "    Loop\r\n"
    "    Close #fn\r\n"
    "End Sub\r\n"
