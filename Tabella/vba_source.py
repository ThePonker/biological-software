    "' PARSE CSV LINE -- quote-aware, handles embedded commas\r\n"
    "' Fix (May 2026): replaces naive Split which corrupted records\r\n"
    "' for any species with multiple commercial projects.\r\n"
    "' =============================================================\r\n"
    "Private Sub ParseCSVLine(line As String, fields() As String, _\r\n"
    "                        ByRef nFields As Long)\r\n"
    "    Dim i As Long\r\n"
    "    Dim L As Long\r\n"
    "    Dim ch As String\r\n"
    "    Dim field As String\r\n"
    "    Dim inQuotes As Boolean\r\n"
    "    Dim QUOTE As String\r\n"
    "    QUOTE = Chr(34)\r\n"
    "    L = Len(line)\r\n"
    "    ReDim fields(0 To 50)\r\n"
    "    nFields = 0\r\n"
    "    field = \"\"\r\n"
    "    inQuotes = False\r\n"
    "    i = 1\r\n"
    "    Do While i <= L\r\n"
    "        ch = Mid(line, i, 1)\r\n"
    "        If inQuotes Then\r\n"
    "            If ch = QUOTE Then\r\n"
    "                If i < L Then\r\n"
    "                    If Mid(line, i + 1, 1) = QUOTE Then\r\n"
    "                        ' Escaped quote inside quoted field\r\n"
    "                        field = field & QUOTE\r\n"
    "                        i = i + 1\r\n"
    "                    Else\r\n"
    "                        inQuotes = False\r\n"
    "                    End If\r\n"
    "                Else\r\n"
    "                    inQuotes = False\r\n"
    "                End If\r\n"
    "            Else\r\n"
    "                field = field & ch\r\n"
    "            End If\r\n"
    "        Else\r\n"
    "            If ch = QUOTE Then\r\n"
    "                inQuotes = True\r\n"
    "            ElseIf ch = \",\" Then\r\n"
    "                fields(nFields) = field\r\n"
    "                nFields = nFields + 1\r\n"
    "                field = \"\"\r\n"
    "            Else\r\n"
    "                field = field & ch\r\n"
    "            End If\r\n"
    "        End If\r\n"
    "        i = i + 1\r\n"
    "    Loop\r\n"
    "    fields(nFields) = field\r\n"
    "    nFields = nFields + 1\r\n"
    "End Sub\r\n"
    "\r\n"
