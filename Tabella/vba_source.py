    "            & \" more matches not shown. Refine your search.)\"\r\n"
    "    End If\r\n"
    "    msg = msg & vbCrLf & \"Enter number (1-\" & maxShow _\r\n"
    "        & \"), or 0 to cancel:\"\r\n"
    "    choice = InputBox(msg, \"Species Lookup\")\r\n"
    "    If Len(choice) = 0 Then\r\n"
    "        PickSpecies = 0\r\n"
    "        Exit Function\r\n"
    "    End If\r\n"
    "    On Error Resume Next\r\n"
    "    num = Val(choice)\r\n"
    "    On Error GoTo 0\r\n"
    "    If num >= 1 And num <= maxShow Then\r\n"
    "        PickSpecies = matches(num)\r\n"
