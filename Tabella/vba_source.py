    "' =============================================================\r\n"
    "Private Sub FuzzyMatch(searchTerm As String, matches() As Long, cnt As Long)\r\n"
    "    Dim words() As String\r\n"
    "    Dim maxMatches As Long\r\n"
    "    Dim i As Long\r\n"
    "    Dim j As Long\r\n"
    "    Dim combined As String\r\n"
    "    Dim allFound As Boolean\r\n"
    "    words = Split(LCase(Trim(searchTerm)), \" \")\r\n"
    "    maxMatches = 20\r\n"
    "    ReDim matches(1 To maxMatches)\r\n"
    "    cnt = 0\r\n"
    "    For i = 1 To pRows\r\n"
    "        combined = LCase(CStr(pData(i, U_NAME)) & \" \" & CStr(pData(i, U_COMMON)))\r\n"
    "        allFound = True\r\n"
    "        For j = LBound(words) To UBound(words)\r\n"
    "            If Len(words(j)) > 0 Then\r\n"
    "                If InStr(1, combined, words(j), vbTextCompare) = 0 Then\r\n"
    "                    allFound = False\r\n"
    "                    Exit For\r\n"
    "                End If\r\n"
    "            End If\r\n"
    "        Next j\r\n"
    "        If allFound Then\r\n"
    "            cnt = cnt + 1\r\n"
    "            If cnt <= maxMatches Then\r\n"
    "                matches(cnt) = i\r\n"
    "            Else\r\n"
    "                Exit For\r\n"
    "            End If\r\n"
    "        End If\r\n"
    "    Next i\r\n"
    "    If cnt > maxMatches Then cnt = maxMatches\r\n"
    "End Sub\r\n"
